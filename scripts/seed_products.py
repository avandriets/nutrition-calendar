def number(value: str) -> Optional[float]:
    return float(value) if value else None


def complete_values(
    name: str,
    calories: float,
    protein: Optional[float],
    carbs: Optional[float],
    fiber: Optional[float],
) -> Tuple[str, float, float, float, float]:
    category = category_for(name)
    protein_value = protein if protein is not None else (
        0.7 if category in {"Фрукты и ягоды", "Овощи и зелень"} else 0.0
    )
    fat = FAT_OVERRIDES.get(name.lower())
    if fat is None:
        if category in {"Фрукты и ягоды", "Овощи и зелень", "Бобовые"}:
            fat = 0.3
        elif category == "Напитки":
            fat = 0.0
        else:
            known_carbs = carbs or 0.0
            known_fiber = fiber or 0.0
            fat = round(max(0.0, (calories - protein_value * 4 - known_carbs * 4 - known_fiber * 2) / 9), 1)
    if carbs is not None:
        carbs_value = carbs
    elif category in {"Мясо и птица", "Рыба и морепродукты", "Яйца"}:
        carbs_value = 0.0
    elif category == "Напитки":
        carbs_value = 3.0
    else:
        carbs_value = round(max(0.0, (calories - protein_value * 4 - fat * 9) / 4), 1)
    return category, protein_value, carbs_value, fiber or 0.0, fat


def seed() -> Tuple[int, int]:
    Base.metadata.create_all(bind=engine)
    db = SessionLocal()
    created = skipped = 0
    try:
        for line in RAW_PRODUCTS.splitlines():
            calorie_text, protein_text, carb_text, fiber_text, name = line.split(";", 4)
            calories = float(calorie_text)
            category, protein, carbs, fiber, fat = complete_values(
                name,
                calories,
                number(protein_text),
                number(carb_text),
                number(fiber_text),
            )
            exists = db.query(Product).filter(
                Product.name == name,
                Product.calories_kcal == calories,
                Product.protein_g == protein,
                Product.carbohydrates_g == carbs,
                Product.fiber_g == fiber,
            ).first()
            if exists:
                skipped += 1
                continue
            db.add(Product(
                name=name,
                category=category,
                description="Импортировано из пользовательской таблицы",
                calories_kcal=calories,
                protein_g=protein,
                fat_g=fat,
                carbohydrates_g=carbs,
                fiber_g=fiber,
            ))
            created += 1
        db.commit()
    finally:
        db.close()
    return created, skipped


if __name__ == "__main__":
    inserted, present = seed()
